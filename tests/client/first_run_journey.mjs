// One disposable authored comparison, explicit choice, offline operation and inheritance.
import assert from 'node:assert/strict';
import {writeFile} from 'node:fs/promises';
import path from 'node:path';
import {openBrowser} from './workplace_fullscreen.mjs';
const [base,out]=process.argv.slice(2);
const api=route=>fetch(base+'/api/'+route).then(r=>{assert.ok(r.ok);return r.json();});
const before=await api('engagements/bookshop/board');
const station=await api(`shifts/${before.latest_shift.id}/investigations`);
const comparison=station.latest_experiment;
assert.equal(comparison.outcome.status,'COMPLETE');
const candidate=comparison.candidates.find(c=>c.label==='B');
const b=await openBrowser(base,out);
try{
 await b.send('Emulation.setDeviceMetricsOverride',{width:1440,height:900,deviceScaleFactor:1,mobile:false});
 await b.send('Page.navigate',{url:base+'/?board=bookshop&guide=1'});
 assert.ok(await b.until(()=>document.body?.dataset.loadState==='ready'&&document.querySelector('[data-guided-panel="4"]')?.hidden===false));
 assert.ok(await b.evaluate(()=>document.getElementById('board-view').getBoundingClientRect().height===0),'first_run: leftover workbench must not appear beside the guided panel');
 const commands=b.commands.length;
 await b.evaluate(()=>document.getElementById('open-choose-b').click());
 assert.ok(await b.until(()=>document.getElementById('choose-dialog').open));
 await b.evaluate(()=>{const input=document.getElementById('selection-rationale');input.value='S47 authored offline browser choice. Check the retained public rates before operating.';input.dispatchEvent(new Event('input',{bubbles:true}));});
 assert.equal(b.commands.length,commands,'opening and writing a reason must not choose');
 await b.evaluate(()=>document.getElementById('select-candidate-b').click());
 assert.ok(await b.until(()=>!document.getElementById('choose-dialog').open&&document.getElementById('selection-note').textContent.includes('is recorded')));
 const chosen=await api('engagements/bookshop/board');
 assert.equal(chosen.operating_selection.selected_version_id,candidate.artifact_version_id);
 assert.equal(chosen.operating_selection.selected_content_hash,candidate.artifact_content_hash);
 assert.equal(chosen.latest_run.id,before.latest_run.id,'choice must not operate');
 assert.ok(await b.evaluate(()=>document.getElementById('open-choose-a').disabled&&document.getElementById('open-choose-b').disabled));
 assert.ok(await b.evaluate(()=>document.getElementById('guided-status').textContent.startsWith('Recommended: Choose.')),'a saved choice recommends explicit operation');
 if (chosen.attempts_remaining === 0) {
   assert.ok(await b.evaluate(()=>document.getElementById('run-shift').disabled),'exhausted attempts must stay blocked');
   await b.evaluate(()=>document.querySelector('[data-first-run-go="5"]').click());
   await b.evaluate(()=>document.getElementById('close-shift').click());
   assert.ok(await b.until(()=>!document.getElementById('open-next-shift').disabled));
   await b.evaluate(()=>document.getElementById('open-next-shift').click());
   assert.ok(await b.until(()=>!document.getElementById('run-shift').disabled));
   const inherited = await api('engagements/bookshop/board');
   assert.equal(inherited.operating_selection.selected_version_id,candidate.artifact_version_id);
   await b.evaluate(()=>document.querySelector('[data-first-run-go="4"]').click());
 }
 await b.evaluate(()=>document.getElementById('run-shift').click());
 assert.ok(await b.until(async()=>{const board=await fetch('/api/engagements/bookshop/board').then(r=>r.json());return board.latest_run?.purpose==='OPERATION'&&['FINALIZED','FAILED'].includes(board.latest_run.state);},30000),'the explicit recorded operation must reach terminal state');
 await b.until(()=>document.getElementById('shift-report').open,1500);
 const operated=await api('engagements/bookshop/board');
 assert.equal(operated.latest_run.selection_id,chosen.operating_selection.id);
 assert.equal(operated.latest_run.artifact_version_id,candidate.artifact_version_id);
 assert.equal(operated.latest_run.evidence_mode,comparison.context_evidence_class);
 if(await b.evaluate(()=>document.getElementById('shift-report').open)) await b.evaluate(()=>document.getElementById('close-shift-report').click());
 await b.evaluate(()=>document.querySelector('[data-first-run-go="5"]').click());
 assert.ok(await b.evaluate(()=>document.getElementById('guided-status').textContent.startsWith('Recommended: Next shift.')));
 await b.evaluate(()=>document.getElementById('guided-review-report').click());
 assert.ok(await b.evaluate(()=>document.getElementById('shift-report').open));
 await b.evaluate(()=>document.getElementById('close-shift-report').click());
 await b.evaluate(()=>document.getElementById('close-shift').click());
 assert.ok(await b.until(()=>!document.getElementById('open-next-shift').disabled));
 const closed=await api('engagements/bookshop/board');assert.equal(closed.latest_shift.state,'closed');
 await b.evaluate(()=>document.getElementById('open-next-shift').click());
 assert.ok(await b.until(old=>document.getElementById('next-state').textContent.includes('open')&&!document.getElementById('next-state').textContent.includes(old),15000,before.latest_shift.id));
 const next=await api('engagements/bookshop/board');
 assert.notEqual(next.latest_shift.id,before.latest_shift.id);
 assert.equal(next.operating_selection.selected_version_id,candidate.artifact_version_id);
 assert.equal(next.operating_selection.selected_content_hash,candidate.artifact_content_hash);
 assert.equal(next.operating_selection.rationale,chosen.operating_selection.rationale);
 assert.equal(next.operating_selection.retained_alternative_version_id,chosen.operating_selection.retained_alternative_version_id);
 assert.deepEqual(b.exceptions,[]);
 await writeFile(path.join(out,'guided-journey.json'),JSON.stringify({label:'Authored offline fixture; no model, Sandbox or learner evidence',selection:chosen.operating_selection,operation:operated.latest_run,inheritedShift:next.latest_shift},null,2));
 console.log('PASS: explicit choice, separate offline operation, consequence review, explicit closure and exact inheritance.');
}finally{await b.close();}
